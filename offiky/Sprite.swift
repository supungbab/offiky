    static var designCount: Int { designs.count }
    static var frameCount: Int { 2 }

    /// 소스 내부의 팔레트 인덱스 격자를 4.1 의 RRGGBB 형식으로 바꾼다
    static func design(at index: Int, frame: Int = 0, tint: Look? = nil) -> Sprite {
        let design = designs[((index % designs.count) + designs.count) % designs.count]
        let rows = design.frames[frame % design.frames.count]
        let palette = design.palette.map { hex in
            tint.map { adjust(hex, by: $0) } ?? hex
        }
        return Sprite(validatedRows: rows.map { row in
            row.map { character in
                guard let slot = character.hexDigitValue, slot < palette.count
                else { return transparent }
                return palette[slot]
            }.joined()
        })
    }

    /// 팔레트 전체에 같은 변환을 적용해 명암 관계를 유지한다
    static func adjust(_ hex: String, by tint: Look) -> String {
        guard let value = UInt32(hex, radix: 16) else { return hex }
        var color = NSColor(
            red: CGFloat((value >> 16) & 0xFF) / 255,
            green: CGFloat((value >> 8) & 0xFF) / 255,
            blue: CGFloat(value & 0xFF) / 255, alpha: 1)
        color = color.usingColorSpace(.sRGB) ?? color
        var h: CGFloat = 0, s: CGFloat = 0, b: CGFloat = 0, a: CGFloat = 0
        color.getHue(&h, saturation: &s, brightness: &b, alpha: &a)
        h = (h + CGFloat(tint.hue)).truncatingRemainder(dividingBy: 1)
        if h < 0 { h += 1 }
        let shifted = NSColor(hue: h,
                              saturation: min(1, s * CGFloat(tint.saturation)),
                              brightness: min(1, b * CGFloat(tint.brightness)), alpha: 1)
        return String(format: "%02x%02x%02x",
                      Int((shifted.redComponent * 255).rounded()),
                      Int((shifted.greenComponent * 255).rounded()),
                      Int((shifted.blueComponent * 255).rounded()))
    }

    static func standard(for id: String) -> Sprite {
        design(at: Int(stableHash(id) % UInt64(designs.count)))
    }

    func cgImage() -> CGImage? {
        let n = Sprite.size
        var pixels = [UInt8](repeating: 0, count: n * n * 4)
        for y in 0..<n {
            let chunks = Sprite.chunks(of: rows[y])
            for x in 0..<n {
                guard chunks[x] != Sprite.transparent,
                      let color = UInt32(chunks[x], radix: 16) else { continue }
                let offset = (y * n + x) * 4
                pixels[offset]     = UInt8((color >> 16) & 0xFF)
                pixels[offset + 1] = UInt8((color >> 8) & 0xFF)
                pixels[offset + 2] = UInt8(color & 0xFF)
                pixels[offset + 3] = 255
            }
        }
        guard let provider = CGDataProvider(data: Data(pixels) as CFData) else { return nil }
        return CGImage(
            width: n, height: n, bitsPerComponent: 8, bitsPerPixel: 32,
            bytesPerRow: n * 4, space: CGColorSpaceCreateDeviceRGB(),
            bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue),
            provider: provider, decode: nil, shouldInterpolate: false,
            intent: .defaultIntent)
    }
