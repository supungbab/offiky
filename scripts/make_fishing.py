EYE, GLINT, MOUTH = (20, 18, 24), (255, 255, 255), (60, 30, 30)
N4 = ((1, 0), (-1, 0), (0, 1), (0, -1))


def render(spec):
    rows = spec["rows"]
    assert len(rows) == 12 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    im = Image.new("RGBA", (16, 12))
    px = im.load()
    cells = {(x, y): c for y, r in enumerate(rows) for x, c in enumerate(r) if c != "."}
    body = {p for p, c in cells.items() if c not in "fr"}
    # 외곽선: 채운 칸 둘레의 빈칸
    for (x, y), c in cells.items():
        if c in "xav":
            continue
        for dx, dy in N4:
            q = (x + dx, y + dy)
            if q not in cells and 0 <= q[0] < 16 and 0 <= q[1] < 12:
                px[q] = (*spec["o"], 255)
    # 열마다 몸의 위아래로 등·옆줄·배를 나눈다
    cols = {}
    for (x, y) in body:
        cols.setdefault(x, []).append(y)
    for (x, y), c in cells.items():
        if c == "#":
            ys = cols[x]
            top, bot = min(ys), max(ys)
            t = 0 if bot == top else (y - top) / (bot - top)
            color = spec["d"] if t < 0.3 else spec["l"] if t < 0.45 else spec["m"] if t < 0.7 else spec["b"]
            if y == bot and bot - top >= 3:
                color = spec["bs"]
        else:
            color = {
                "f": spec["f"] if x % 2 == 0 else spec["fd"],
                "r": spec["f"] if y % 2 == 0 else spec["fd"],
                "e": EYE, "w": GLINT, "m": MOUTH, "g": spec["g"], "s": spec["s"], "t": spec["t"],
                "h": spec["l"], "b": spec["b"], "d": spec["d"], "x": spec["o"], "k": spec["l"], "a": spec["m"], "A": spec["m"], "u": (150, 90, 50), "v": spec["l"], **spec.get("extra", {}),
            }[c]
        px[(x, y)] = (*color, 255)
    return im


def fishes():
    sheet = Image.new("RGBA", (16 * len(FISH), 12))
    for n, spec in enumerate(FISH.values()):
        sheet.paste(render(spec), (16 * n, 0))
    return sheet


def dock():
    """낚시꾼이 올라서는 나무 발판(24x6). 널빤지 두 줄 아래로 기둥 둘이 물속으로 내려간다"""
    im, put = canvas(24, 6)
    put([(x, y) for x in range(24) for y in (0, 1)], (176, 124, 72, 255))
    put([(x, 0) for x in range(24)], (204, 150, 92, 255))
    put([(x, y) for x in (5, 6, 11, 12, 17, 18) for y in (0, 1)], (140, 96, 56, 255))
    put([(x, 2) for x in range(24)], LINE)
    for px in (3, 19):
        put([(px, y) for y in range(2, 6)] + [(px + 1, y) for y in range(2, 6)], (110, 76, 44, 255))
        put([(px + 1, y) for y in range(3, 6)], (80, 54, 32, 255))
    return im


